"""
python debug_all_themes.py
Виводить ВСІ теми класифікатора Ради з кількістю документів
"""
import requests
from bs4 import BeautifulSoup
import re
import time

HEADERS = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36",
    "Accept-Language": "uk-UA,uk;q=1.0",
    "Accept": "text/html,application/xhtml+xml,*/*",
    "Cookie": "lang=uk",
}
BASE = "https://zakon.rada.gov.ua"

def get_all_themes():
    url = f"{BASE}/laws/main/a/stru8?lang=uk"
    r = requests.get(url, headers=HEADERS, timeout=15)
    soup = BeautifulSoup(r.text, "html.parser")

    themes = []
    seen = set()
    for a in soup.find_all("a", href=True):
        href = a["href"]
        text = a.text.strip()
        # Тільки h-розділи типу h1, h2, h14, h21...
        # href може бути як /laws/main/h14 так і https://zakon.rada.gov.ua/laws/main/h14
        m = re.search(r"/laws/main/(h\d+)$", href)
        if m and text and m.group(1) not in seen:
            seen.add(m.group(1))
            themes.append({"code": m.group(1), "title": text})

    return themes

def get_page_count(code: str) -> int:
    url = f"{BASE}/laws/main/{code}/page?lang=uk"
    try:
        r = requests.get(url, headers=HEADERS, timeout=15)
        soup = BeautifulSoup(r.text, "html.parser")
    except Exception:
        return 0

    max_page = 1
    for a in soup.find_all("a", href=True):
        m = re.search(rf"/laws/main/{re.escape(code)}/page(\d+)", a["href"])
        if m:
            max_page = max(max_page, int(m.group(1)))

    for tag in soup.find_all(string=True):
        t = tag.strip()
        m = re.search(r'з\s+([\d\s]+)', t)
        if m and "документ" in t.lower():
            total = int(m.group(1).replace(" ", ""))
            max_page = max(max_page, (total + 49) // 50)
            break

    return max_page

if __name__ == "__main__":
    themes = get_all_themes()
    print(f"Знайдено тем: {len(themes)}\n")
    print(f"{'Код':<10} {'Сторінок':>10}   Назва")
    print("-" * 80)

    for t in themes:
        pages = get_page_count(t["code"])
        docs  = pages * 50
        print(f"{t['code']:<10} {pages:>5} стор (~{docs:>6} док)   {t['title'][:55]}")
        time.sleep(0.3)


